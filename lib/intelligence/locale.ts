export function translate(locale: Locale, key: Key) {
  return { en, fr, rw }[locale][key];
}
export function screeningPrompt(
  locale: Locale,
  competency: string,
  followUp = false,
) {
  if (locale === "fr")
    return followUp
      ? "Précisez vos actions, le résultat et une preuve concrète."
      : "Décrivez une situation précise liée à " +
          competency +
          ". Qu’avez-vous fait, pourquoi et avec quel résultat ?";
  if (locale === "rw")
    return followUp
      ? "Sobanura ibyo wakoze, ibyavuyemo n’ikimenyetso gifatika."
      : "Sobanura urugero rujyanye na " +
          competency +
          ". Wakoze iki, kubera iki, kandi byagenze bite?";
  return followUp
    ? "Clarify your own actions, the outcome and a concrete piece of evidence."
    : "Describe a specific situation involving " +
        competency +
        ". What did you do, why, and what was the outcome?";
}
